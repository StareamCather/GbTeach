def bounded_steps(session, count, deadline):
    before = actual_stats(session)
    require(before["paused"], "Controlled active-phase cut requires a paused world")
    target = before["iterations"]+count
    session.step(count)
    while time.monotonic() < deadline:
        after = actual_stats(session)
        require(after["iterations"] <= target and after["paused"], "Owned multistep escaped its exact paused budget")
        if after["iterations"] == target:
            return {"before": before, "after": after, "requested_steps": count}
    raise RuntimeError("Controlled phase-cut multistep acknowledgement exceeded its deadline")


def paused_active_phase_cut(session):
    """Interrupt a real moving multi-turn phase through the public request path."""
    deadline = time.monotonic()+45
    session.pause(True)
    speed_episode = "acceptance-speed-cut-"+uuid.uuid4().hex
    torque_episode = "acceptance-torque-cut-"+uuid.uuid4().hex
    original_files = source_hashes(session.workspace)
    request_phase(session, speed_episode, "speed-p")
    speed_steps = bounded_steps(session, 3000, deadline)
    moving = read_json(control_directory(session)/"status.json")
    require(moving["episode"] == speed_episode and moving["phase"] == "speed-p"
            and moving["active"] is True and moving["phase_complete"] is False,
            "Controlled cut did not actually interrupt an active speed phase")
    request_phase(session, torque_episode, "torque")
    cut_steps = bounded_steps(session, 20, deadline)
    accepted = read_json(control_directory(session)/"status.json")
    require(accepted["episode"] == torque_episode and accepted["phase"] == "torque" and not accepted["error"],
            "Paused active-phase request failed to initialize the actual torque experiment")
    reset = accepted["reset_evidence"]
    verified_reset = validate_encoder_reset(reset)
    require(abs(float(reset["pre_init_q_rad"])) > .05 and abs(float(reset["pre_init_omega_rad_s"])) > .5,
            "Phase-cut regression did not initialize from a genuinely moving nonzero state")
    completion_steps = bounded_steps(session, 1000, deadline)
    finished = read_json(control_directory(session)/"status.json")
    require(finished["episode"] == torque_episode and finished["phase_complete"] is True and not finished["error"],
            "Interrupted torque phase did not complete its honest physical response")
    trace = read_trace(session)
    previous = numeric_rows([row for row in trace if row["episode"] == speed_episode])
    require(previous and abs(previous[-1]["q_unwrapped_after_rad"]) > 2*math.pi,
            "Active cut lacks actual accumulated multi-turn motion")
    difference = math.atan2(math.sin(float(reset["pre_init_q_rad"])-previous[-1]["q_after_rad"]),
                            math.cos(float(reset["pre_init_q_rad"])-previous[-1]["q_after_rad"]))
    close(difference, 0., "Cut pre-initialization encoder and actual preceding trace", 1e-7)
    close(float(reset["pre_init_omega_rad_s"]), previous[-1]["omega_after_rad_s"], "Cut pre-initialization actual velocity", 1e-7)
    records = [row for row in trace if row["episode"] == torque_episode]
    metrics = independent_phase(records, "torque", read_json(session.workspace/"parameters.json"), digest(session.workspace/"parameters.json"))
    require(original_files == source_hashes(session.workspace) and actual_stats(session)["paused"],
            "Controlled active-phase cut changed exercise files or lost paused state")
    return {"name": "paused_moving_multiturn_phase_cut_to_real_torque", "passed": True,
            "protocol": "native phase.request and owned exact world multisteps; no test pose/velocity writes",
            "interrupted_episode": speed_episode, "new_episode": torque_episode,
            "moving_phase_completed_steps": len(previous), "actual_before_cut_unwrapped_q_rad": previous[-1]["q_unwrapped_after_rad"],
            "actual_before_cut_omega_rad_s": previous[-1]["omega_after_rad_s"],
            "independent_initializer_evidence": verified_reset, "native_reset_evidence": reset,
            "step_acknowledgements": [speed_steps, cut_steps, completion_steps], "actual_torque_response": metrics}


def configuration_regressions(lesson, private):
    """A concrete saturation-visibility risk, without a simulator or phase request."""
    module = types.ModuleType("_l10_configuration_risk_probe")
    module.__file__ = str(lesson.folder/"config.py")
    exec(compile((lesson.folder/"config.py").read_bytes(), module.__file__, "exec"), module.__dict__)
    folder = private/"config-risk"
    folder.mkdir()
    path = folder/"parameters.json"
    original = (lesson.folder/"parameters.json").read_bytes()
    path.write_bytes(original)
    baseline = module.read_parameters(path)
    write_parameters(folder, speed_p_kp=.8)
    changed = module.read_parameters(path)
    require(changed["speed_pi_kp"] == baseline["speed_pi_kp"]
            and changed["speed_pi_ki"] == baseline["speed_pi_ki"], "Single P-gain variant changed the paired PI controller")
    path.write_bytes(original)
    write_parameters(folder, velocity_target_rad_s=2., load_torque_Nm=.1, saturation_limit_Nm=.45)
    bad = path.read_bytes()
    try:
        module.read_parameters(path)
    except ValueError as error:
        require("saturation_limit_Nm" in str(error), "Saturation-signal failure lacks its relevant diagnosis")
        diagnosis = str(error)
    else:
        raise AssertionError("A cap above the target's required torque was accepted as a saturation demonstration")
    require(path.read_bytes() == bad, "Configuration validator modified its input")
    path.write_bytes(original)
    restored = module.read_parameters(path)
    require(restored == baseline and path.read_bytes() == original, "Configuration risk repair failed byte-for-byte")
    return {"kind": "configuration_risk_not_physics", "gazebo_started": False,
            "baseline_accepted": baseline, "P_only_gain_variant_accepted": changed,
            "unobservable_saturation_rejected": {"velocity_target_rad_s": 2., "load_torque_Nm": .1,
                                                 "saturation_limit_Nm": .45, "required_target_torque_Nm": .3,
                                                 "diagnosis": diagnosis},
            "original_bytes_restored_and_reaccepted": True}


def validate_encoder_reset(reset):
    """Check the full-state phase initializer, not a guessed counter-error cause."""
    require(reset["initializer_method"] == "captured_absolute_link_pose_then_native_counter_sync",
            "Unknown phase initialization method")
    require(reset["counter_sync_called"] is True and reset["counter_sync_calls"] == 1,
            "Native counter must be synchronized exactly once at the phase boundary")
    require(reset["counter_sync_api"] == "OpenDE C API via public ODELink.GetODEId/body joint enumeration",
            "Counter synchronization must use the approved public OpenDE API route")
    handle = reset["native_counter_handle"]
    require(handle["body_joint_count"] == 1 and handle["joint_type"] == "hinge"
            and handle["rotor_body_matches"] is True and handle["other_body_is_world"] is True,
            "Public native handle did not uniquely identify this rotor's world hinge")
    require(handle["sdk_joint_identity_unchanged"] is True
            and handle["initial_sdk_joint_id"] == handle["current_sdk_joint_id"],
            "Phase initialization replaced the actual SDK joint identity")
    for native_key, sdk_key, expected in (("anchor_world_m", "sdk_anchor_world_m", (0., 0., .6)),
                                           ("axis_world", "sdk_axis_world", (0., 0., 1.))):
        native, sdk = handle[native_key], handle[sdk_key]
        require(len(native) == 3 and len(sdk) == 3, "Incomplete actual native/SDK hinge geometry evidence")
        for native_value, sdk_value, desired in zip(native, sdk, expected):
            close(float(native_value), desired, "Actual public OpenDE hinge "+native_key, 1e-9)
            close(float(sdk_value), desired, "Actual SDK hinge "+sdk_key, 1e-9)
            close(float(native_value), float(sdk_value), "Native handle and SDK hinge match", 1e-9)
    captured = reset["captured_initial_world_pose"]
    require(len(captured) == 7, "Captured Load-time world pose must contain xyz and quaternion")
    for actual, expected in zip(captured[:3], (0., 0., .6)):
        close(float(actual), expected, "Actual captured nominal rotor position", 1e-7)
    quaternion = [float(value) for value in captured[3:]]
    require(min(sum((a-b)**2 for a, b in zip(quaternion, sign)) for sign in ((1., 0., 0., 0.), (-1., 0., 0., 0.))) <= 1e-14,
            "Captured initial rotor orientation does not match the fixed nominal zero pose")
    for field in ("pre_init_world_pose", "pre_counter_world_pose", "post_world_pose"):
        pose = [float(value) for value in reset[field]]
        require(len(pose) == 7 and all(math.isfinite(value) for value in pose), "Invalid actual initialization pose")
        close(sum(value*value for value in pose[3:]), 1., "Actual initialization quaternion norm", 1e-7)
        if field != "pre_init_world_pose":
            require(math.sqrt(sum((a-float(b))**2 for a, b in zip(pose[:3], captured[:3]))) <= 1e-7,
                    "Full-state initializer did not restore the captured absolute rotor position")
            require(min(math.sqrt(sum((a-sign*b)**2 for a, b in zip(pose[3:], quaternion))) for sign in (-1., 1.)) <= 1e-7,
                    "Full-state initializer did not restore the captured absolute rotor orientation")
    require(all(math.isfinite(float(reset[key])) for key in ("pre_init_q_rad", "pre_init_omega_rad_s")),
            "Initialization must preserve finite observed pre-initialization joint evidence")
    for field in ("pre_counter_omega_rad_s", "post_q_rad", "post_omega_rad_s"):
        close(float(reset[field]), 0., "Actual SDK initialization evidence "+field, 1e-7)
    for field in ("pre_counter_world_x_axis", "post_world_x_axis"):
        axis = reset[field]
        require(len(axis) == 3, "Reset must contain a complete measured world X axis")
        for actual, expected in zip(axis, (1., 0., 0.)):
            close(float(actual), expected, "Actual reset rotor world zero axis", 1e-7)
    pre = float(reset["pre_counter_q_rad"])
    require(math.isfinite(pre), "Pre-correction SDK encoder is non-finite")
    offset_removed = reset["counter_offset_removed"]
    require(isinstance(offset_removed, bool) and offset_removed is (abs(pre) > 1e-7),
            "Counter offset flag disagrees with its observed pre-counter value")
    require(reset["counter_correction_applied"] is offset_removed, "Legacy correction flag differs from the offset observation")
    return {"actual_pre_init_q_rad": reset["pre_init_q_rad"], "actual_pre_init_omega_rad_s": reset["pre_init_omega_rad_s"],
            "actual_pre_counter_q_rad": pre, "counter_offset_removed": offset_removed,
            "counter_correction_applied": offset_removed, "counter_sync_called": True, "counter_sync_calls": 1,
            "counter_sync_api": reset["counter_sync_api"], "actual_native_counter_handle": handle,
            "actual_post_q_rad": reset["post_q_rad"],
            "actual_post_omega_rad_s": reset["post_omega_rad_s"],
            "real_zero_pose_and_velocity_confirmed_before_counter_correction": True}


def encoder_reset_regressions():
    zero_pose = [0., 0., .6, 1., 0., 0., 0.]
    example = {"initializer_method": "captured_absolute_link_pose_then_native_counter_sync",
               "counter_sync_api": "OpenDE C API via public ODELink.GetODEId/body joint enumeration",
               "native_counter_handle": {"body_joint_count": 1, "joint_type": "hinge", "rotor_body_matches": True,
                                         "other_body_is_world": True, "anchor_world_m": [0., 0., .6],
                                         "axis_world": [0., 0., 1.], "sdk_anchor_world_m": [0., 0., .6],
                                         "sdk_axis_world": [0., 0., 1.], "initial_sdk_joint_id": 42,
                                         "current_sdk_joint_id": 42, "sdk_joint_identity_unchanged": True},
               "pre_init_q_rad": .37, "pre_init_omega_rad_s": 1.2,
               "pre_init_world_pose": [0., 0., .6, math.cos(.37/2), 0., 0., math.sin(.37/2)],
               "captured_initial_world_pose": zero_pose, "pre_counter_world_pose": zero_pose,
               "post_world_pose": zero_pose, "counter_sync_called": True, "counter_sync_calls": 1,
               "counter_offset_removed": True, "pre_counter_q_rad": .123, "pre_counter_omega_rad_s": 0.,
               "pre_counter_world_x_axis": [1., 0., 0.], "counter_correction_applied": True,
               "post_q_rad": 0., "post_omega_rad_s": 0., "post_world_x_axis": [1., 0., 0.]}
    valid = validate_encoder_reset(example)
    rejected = []
    for field, value in (("counter_sync_called", False), ("counter_sync_calls", 2),
                         ("native_counter_handle", dict(example["native_counter_handle"], body_joint_count=2)),
                         ("native_counter_handle", dict(example["native_counter_handle"], other_body_is_world=False)),
                         ("native_counter_handle", dict(example["native_counter_handle"], axis_world=[1., 0., 0.])),
                         ("native_counter_handle", dict(example["native_counter_handle"], current_sdk_joint_id=43)),
                         ("pre_counter_world_pose", [.01, 0., .6, 1., 0., 0., 0.]),
                         ("pre_counter_world_x_axis", [1., .01, 0.]), ("post_q_rad", .1)):
        invalid = dict(example)
        invalid[field] = value
        try:
            validate_encoder_reset(invalid)
        except AssertionError as error:
            rejected.append({"field": field, "diagnosis": str(error)})
        else:
            raise AssertionError("Encoder evidence checker accepted a hidden physical initialization error")
    return {"kind": "numerical_full_state_initialization_evidence_not_physics", "valid_full_state_example": valid,
            "rejected_physical_or_counter_mismatches": rejected}


def reset_only_main(args):
    """One public reset_models regression, separate from the full six-phase run."""
    lessons, errors = load_catalog(ROOT)
    candidates = [candidate for candidate in lessons if candidate.key == KEY]
