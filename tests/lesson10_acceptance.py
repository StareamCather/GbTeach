def phase_gains(parameters, phase):
    if phase == "torque":
        return (0., 0., 0., parameters["command_limit_Nm"])
    if phase in ("speed-p", "speed-pi", "saturation"):
        return (parameters["speed_p_kp"] if phase == "speed-p" else parameters["speed_pi_kp"],
                0. if phase == "speed-p" else parameters["speed_pi_ki"], 0.,
                parameters["saturation_limit_Nm"] if phase == "saturation" else parameters["command_limit_Nm"])
    return (parameters["position_kp"], 0., parameters["position_kd"] if phase == "position-pd" else 0., parameters["command_limit_Nm"])


def numeric_rows(records):
    text = {"episode", "phase", "controller_mode", "config_sha256"}
    return [{key: value if key in text else float(value) for key, value in row.items()} for row in records]


def independent_phase(records, phase, parameters, sha):
    rows = numeric_rows(records)
    require(len(rows) == round(DURATIONS[phase]/DT), "Missing native 1 kHz pre/post steps for "+phase)
    require(all(row["phase"] == phase and row["config_sha256"] == sha for row in rows),
            "Native trace phase or frozen parameter SHA mismatch")
    mode = "force" if phase == "torque" else ("position" if phase.startswith("position") else "velocity")
    require(all(row["controller_mode"] == mode for row in rows), "Native controller mode does not match the teaching phase")
    require(all(math.isfinite(value) for row in rows for value in row.values() if isinstance(value, float)), "Non-finite native motor trace")
    kp, ki, kd, cap = phase_gains(parameters, phase)
    integral = previous_error = 0.
    maximum_command_error = maximum_q_integral_error = 0.
    close(rows[0]["q_before_rad"], 0., "Actual phase initial joint position", 1e-7)
    close(rows[0]["omega_before_rad_s"], 0., "Actual phase initial angular velocity", 1e-7)
    unwrapped = rows[0]["q_before_rad"]
    for index, row in enumerate(rows):
        close(row["phase_step"], index+1, "Explicit phase step index")
        close(row["phase_elapsed_s"], (index+1)*DT, "Post-step elapsed time")
        close(row["dt_s"], DT, "Native controller dt", 1e-10)
        close(row["sim_time_s"]-rows[0]["sim_time_s"], index*DT,
              "Actual world-clock advancement between successive pre/post pairs", 1e-8)
        if index:
            close(row["omega_before_rad_s"], rows[index-1]["omega_after_rad_s"], "Native pre/post velocity continuity", 1e-7)
            # Joint positions may be reported modulo 2*pi; compare increments in the local branch.
            jump = math.atan2(math.sin(row["q_before_rad"]-rows[index-1]["q_after_rad"]),
                              math.cos(row["q_before_rad"]-rows[index-1]["q_after_rad"]))
            close(jump, 0., "Native pre/post joint-position continuity", 1e-7)
        load = (parameters["load_torque_Nm"] if phase in ("speed-p", "speed-pi", "saturation")
                and row["phase_elapsed_s"]-DT >= parameters["load_start_s"]-EPS else 0.)
        close(row["load_torque_Nm"], load, "Actual signed resisting load")
        close(row["joint_applied_Nm"], row["motor_command_Nm"]-load, "Native post-load GetForce ledger", 1e-7)
        require(abs(row["motor_command_Nm"]) <= cap+1e-8, "Native motor output exceeded its configured cap")
        if phase == "torque":
            close(row["motor_command_Nm"], parameters["torque_command_Nm"], "Open-loop force command")
        else:
            position = phase.startswith("position")
            error = (row["q_before_rad"]-parameters["position_target_rad"] if position else
                     row["omega_before_rad_s"]-parameters["velocity_target_rad_s"])
            replay = pid_update(error, row["dt_s"], kp, ki, kd, parameters["integral_term_limit_Nm"], cap, integral, previous_error)
            integral, previous_error = replay["integral"], replay["previous"]
            for key, expected in (("pid_p_gain", kp), ("pid_i_gain", ki), ("pid_d_gain", kd),
                                  ("pid_p_error", error), ("pid_i_error", integral), ("pid_d_error", replay["derivative"]),
                                  ("pid_i_term_Nm", replay["i_term"]), ("pid_raw_command_Nm", replay["raw"]),
                                  ("motor_command_Nm", replay["command"])):
                close(row[key], expected, "Independent native PID replay "+key, 2e-6)
            maximum_command_error = max(maximum_command_error, abs(row["motor_command_Nm"]-replay["command"]))
        angular_step = math.atan2(math.sin(row["q_after_rad"]-row["q_before_rad"]),
                                 math.cos(row["q_after_rad"]-row["q_before_rad"]))
        unwrapped += angular_step
        close(row["q_unwrapped_after_rad"], unwrapped, "Independent wrap-aware encoder accumulation", 1e-6)
        local_bound = DT*abs(row["omega_after_rad_s"]-row["omega_before_rad_s"])+2e-6
        q_error = abs(angular_step-DT*(row["omega_before_rad_s"]+row["omega_after_rad_s"])/2)
        require(q_error <= local_bound, "Native joint displacement is inconsistent with the sampled angular velocities")
        maximum_q_integral_error = max(maximum_q_integral_error, q_error)
        close(row["rotor_x_axis_x"], math.cos(row["q_after_rad"]), "Actual rotor X axis cosine", .002)
        close(row["rotor_x_axis_y"], math.sin(row["q_after_rad"]), "Actual rotor X axis sine", .002)
    result = {"phase": phase, "actual_steps": len(rows), "first_actual_prestate": rows[0], "last_actual_poststate": rows[-1],
              "frozen_parameter_sha256": sha, "independent_momentum_balance": momentum_metrics(rows),
              "maximum_replayed_command_difference_Nm": maximum_command_error,
              "maximum_q_velocity_integral_difference_rad": maximum_q_integral_error}
    if phase == "torque":
        observations = []
        tau = parameters["torque_command_Nm"]
        for elapsed in (.2, .5):
            row = rows[round(elapsed/DT)-1]
            predicted_w = tau/B*(1-math.exp(-B*elapsed/J))
            predicted_q = tau/B*(elapsed-J/B*(1-math.exp(-B*elapsed/J)))
            close(row["omega_after_rad_s"], predicted_w, "Real open-loop rotor angular velocity", .02)
            close(row["q_unwrapped_after_rad"], predicted_q, "Real open-loop rotor rotation", .015)
            observations.append({"t_s": elapsed, "actual_omega_rad_s": row["omega_after_rad_s"],
                                 "actual_q_rad": row["q_unwrapped_after_rad"], "analytic_omega_rad_s": predicted_w, "analytic_q_rad": predicted_q})
        result["actual_open_loop_observations"] = observations
    elif phase in ("speed-p", "speed-pi", "saturation"):
        tail = [row for row in rows if 5-EPS <= row["phase_elapsed_s"] <= 6+EPS]
        mean_w = sum(row["omega_after_rad_s"] for row in tail)/len(tail)
        error_rms = math.sqrt(sum((row["omega_after_rad_s"]-parameters["velocity_target_rad_s"])**2 for row in tail)/len(tail))
        result.update(actual_tail_samples=len(tail), actual_mean_omega_rad_s=mean_w, actual_tracking_error_RMS_rad_s=error_rms)
        if phase == "speed-p":
            equilibrium = (kp*parameters["velocity_target_rad_s"]-parameters["load_torque_Nm"])/(kp+B)
            close(mean_w, equilibrium, "Actual loaded proportional speed equilibrium", .03)
            result["current_configuration_equilibrium_rad_s"] = equilibrium
        elif phase == "speed-pi":
            require(error_rms <= .02, "Actual PI speed tracking did not remove the declared loaded steady error")
        else:
            equilibrium = (cap-parameters["load_torque_Nm"])/B
            close(mean_w, equilibrium, "Actual torque-limited steady speed", .04)
            require(max(abs(row["motor_command_Nm"]) for row in rows) >= cap-1e-6, "Saturation trial never reached its actual output cap")
            require(max(abs(row["pid_i_term_Nm"]) for row in rows) >= parameters["integral_term_limit_Nm"]-1e-6,
                    "Saturation trial never demonstrated the integral-output cap")
    else:
        target = parameters["position_target_rad"]
        direction = 1. if target > 0 else -1.
        peak = max(direction*row["q_unwrapped_after_rad"] for row in rows)
        tail = [row for row in rows if 2-EPS <= row["phase_elapsed_s"] <= 3+EPS]
        mean_error = sum(abs(row["q_unwrapped_after_rad"]-parameters["position_target_rad"]) for row in tail)/len(tail)
        omega_rms = math.sqrt(sum(row["omega_after_rad_s"]**2 for row in tail)/len(tail))
        result.update(actual_peak_position_in_target_direction_rad=peak, target_magnitude_rad=abs(target),
                      actual_peak_to_target_ratio=peak/abs(target), actual_tail_mean_absolute_position_error_rad=mean_error,
                      actual_tail_omega_RMS_rad_s=omega_rms, actual_tail_samples=len(tail))
        if phase == "position-p":
            require(peak > 1.25*abs(target), "Actual position-P trajectory lacks the predeclared relative overshoot")
        else:
            require(peak < 1.05*abs(target) and mean_error < .01 and omega_rms < .03,
                    "Actual PD position trajectory failed its predeclared settling/overshoot bounds")
    return result


def native_model(status):
    expected = {"mass_kg": 1., "radius_m": .25, "length_m": .06, "Ixx_kg_m2": .015925,
                "Iyy_kg_m2": .015925, "Izz_kg_m2": J, "damping_Nms_rad": B,
                "effort_limit_Nm": 3., "physics_step_s": DT, "gravity_z": -9.81}
    for key, value in expected.items():
        close(float(status["model"][key]), value, "Actual SDK motor model "+key, 1e-9)
    axis = status["model"]["axis_xyz"]
    require(len(axis) == 3 and all(abs(float(a)-b) <= 1e-9 for a, b in zip(axis, (0., 0., 1.))),
            "Actual revolute axis is not +Z")
    return {"actual": status["model"], "expected": expected}


def await_ready(session, timeout=15):
    deadline = time.monotonic()+timeout
    last = None
    while time.monotonic() < deadline:
        require(session.running, "Motor server exited before the instrument became ready")
        try:
            last = read_json(control_directory(session)/"status.json")
            if last["config_sha256"] == digest(session.workspace/"parameters.json"):
                require(not last["error"], "Native motor instrument error: "+str(last["error"]))
                close_world = last["world_sha256"] == digest(session.workspace/"world.sdf")
                require(close_world, "Native motor instrument did not identify the loaded world bytes")
                native_model(last)
                return last
        except (OSError, ValueError, KeyError):
            pass
        time.sleep(.05)
    raise AssertionError("No ready native motor status with the current configuration SHA: "+repr(last))


def signature(session):
    status = read_json(control_directory(session)/"status.json")
    return {key: status[key] for key in ("episode", "phase", "phase_step", "config_sha256", "world_sha256")}


def verify_case(session, name, failure_diagnostic=None):
    original = actual_stats(session)
    files = source_hashes(session.workspace)
    prior_signature = signature(session)
    trace = control_directory(session)/"control.csv"
    prior_trace_sha = digest(trace)
    prior_episodes = {row["episode"] for row in read_trace(session)}
    item = {"name": name, "passed": False, "original_stats": original,
            "state_contract": "phase resets keep final results; restore pause and preserve exercise files"}
    offset = session.log_path.stat().st_size
    result = session.verify()
    output = session.log_path.read_bytes()[offset:].decode("utf-8", errors="replace")
    item.update(verifier_result=result, raw_verifier_output=output)
    after = actual_stats(session)
    require(after["paused"] == original["paused"], "Motor verifier did not restore actual original pause")
    require(files == source_hashes(session.workspace), "Motor verifier changed personal exercise files")
    item.update(stats_after=after, pause_preserved=True, exercise_files_unchanged=True)
    if failure_diagnostic:
        require(original["paused"], "Invalid motor input checks require a paused valid server")
        require(result["passed"] is False and failure_diagnostic.lower() in output.lower(),
                "Invalid motor input lacks its expected relevant diagnosis: "+failure_diagnostic+"\n"+output)
        require(original["iterations"] == after["iterations"]
                and original["sim_time_sec_nsec"] == after["sim_time_sec_nsec"], "Invalid motor input controlled physics before rejection")
        require(prior_signature == signature(session) and prior_trace_sha == digest(trace),
                "Rejected motor input started a phase, reset the plant, or appended control samples")
        item.update(rejected_before_control=True, native_signature_unchanged=True, trace_bytes_unchanged=True)
    else:
        require(result["passed"] is True, "Actual canonical motor verification failed: "+output)
        canonical = read_json(control_directory(session)/"verification.json")
        parameters = read_json(session.workspace/"parameters.json")
        require(canonical["passed"] is True and canonical["parameters"] == parameters,
                "Canonical report does not use the current private parameters")
        require([phase["phase"] for phase in canonical["phases"]] == list(DURATIONS), "Motor verifier omitted/reordered a teaching phase")
        all_rows = read_trace(session)
        measured = []
        for phase in canonical["phases"]:
            episode = phase["episode"]
            require(episode not in prior_episodes, "Motor verifier reused an old episode instead of running the current experiment")
            records = [row for row in all_rows if row["episode"] == episode and row["phase"] == phase["phase"]]
            reset = phase["reset_evidence"]
            require(reset["commands_empty"] is True, "Native JointController target/feedforward maps were not reset")
            for key in ("p_error", "i_error", "d_error", "command_Nm"):
                close(float(reset[key]), 0., "Actual native phase-reset state "+key)
            verified_reset = validate_encoder_reset(reset)
            actual = independent_phase(records, phase["phase"], parameters, digest(session.workspace/"parameters.json"))
            actual["independent_native_encoder_reset"] = verified_reset
            close(float(reset["post_q_rad"]), float(records[0]["q_before_rad"]), "SDK reset and first real CSV position", 1e-7)
            close(float(reset["post_omega_rad_s"]), float(records[0]["omega_before_rad_s"]), "SDK reset and first real CSV velocity", 1e-7)
            measured.append(actual)
        multiturn = [item["phase"] for item in measured if abs(item["last_actual_poststate"]["q_unwrapped_after_rad"]) > 2*math.pi]
        require(multiturn, "Motor cycle did not actually exercise multi-turn encoder trajectories")
        item.update(canonical_measurements=canonical, independent_actual_phases=measured,
                    actual_model=native_model(read_json(control_directory(session)/"status.json")),
                    actual_multiturn_phases=multiturn,
                    actual_counter_sync_call_count=sum(phase["independent_native_encoder_reset"]["counter_sync_calls"] for phase in measured),
                    actual_counter_offset_removed_count=sum(phase["independent_native_encoder_reset"]["counter_offset_removed"] for phase in measured))
    item["passed"] = True
    return item


