def negative_group(session):
    params = session.workspace/"parameters.json"
    world = session.workspace/"world.sdf"
    original_params, original_world = params.read_bytes(), world.read_bytes()
    checks = []
    for name, changes, diagnostic in (
        ("NaN_gain_before_control", {"speed_p_kp": float("nan")}, "speed_p_kp"),
        ("negative_gain_before_control", {"speed_pi_ki": -1.}, "speed_pi_ki"),
        ("negative_motor_limit_before_control", {"command_limit_Nm": -1.}, "command_limit_Nm"),
    ):
        try:
            write_parameters(session.workspace, **changes)
            checks.append(verify_case(session, name, diagnostic))
        finally:
            params.write_bytes(original_params)
    try:
        tree = ET.parse(str(world))
        candidates = tree.getroot().findall(".//inertial/inertia/izz")
        require(candidates, "No rotor inertia field in current SDF")
        candidates[0].text = "-0.1"
        tree.write(str(world), encoding="utf-8", xml_declaration=True)
        checks.append(verify_case(session, "changed_invalid_world_before_control", "world"))
    finally:
        world.write_bytes(original_world)
    return {"name": "invalid_parameters_and_world_rejected_before_physics", "passed": True,
            "checks": checks, "original_parameter_bytes_restored": params.read_bytes() == original_params,
            "original_world_bytes_restored": world.read_bytes() == original_world}


