def close(actual, expected, label, tolerance=1e-8):
    require(math.isfinite(actual) and math.isfinite(expected) and abs(actual-expected) <= tolerance,
            "{}: observed {}, expected {} +/- {}".format(label, actual, expected, tolerance))


def clip(value, limit):
    return max(-limit, min(limit, value))


def pid_update(error, dt, kp, ki, kd, i_limit, command_limit, integral, previous):
    """Independent replay of Classic11 PID.cc: current-target and output I clamp.

    https://github.com/gazebosim/gazebo-classic/blob/gazebo11_11.15.1/gazebo/common/PID.cc
    GetErrors' integral is a raw integral; the cap applies to Ki*integral.
    """
    require(dt > 0 and math.isfinite(error), "Replay requires a finite error and positive actual controller dt")
    integral += error*dt
    i_term = ki*integral
    if i_term > i_limit:
        i_term = i_limit
        integral = i_term/ki
    elif i_term < -i_limit:
        i_term = -i_limit
        integral = i_term/ki
    derivative = (error-previous)/dt
    raw = -(kp*error+i_term+kd*derivative)
    return {"integral": integral, "derivative": derivative, "i_term": i_term,
            "raw": raw, "command": clip(raw, command_limit), "previous": error}


def momentum_metrics(rows):
    """Compare impulse and momentum, bracketing explicit/implicit viscous damping."""
    impulse = sum((row["motor_command_Nm"]-row["load_torque_Nm"])*row["dt_s"] for row in rows)
    before_damping = B*sum(row["omega_before_rad_s"]*row["dt_s"] for row in rows)
    after_damping = B*sum(row["omega_after_rad_s"]*row["dt_s"] for row in rows)
    change = J*(rows[-1]["omega_after_rad_s"]-rows[0]["omega_before_rad_s"])
    midpoint_residual = change-impulse+(before_damping+after_damping)/2
    # Fixed explicit ODE damping uses pre-step velocity. Freeze a 2e-5 Nms
    # numerical floor plus ten ppm of commanded impulse before physical runs.
    explicit_residual = change-impulse+before_damping
    numerical_allowance = 2e-5+1e-5*sum(abs(row["joint_applied_Nm"])*row["dt_s"] for row in rows)
    require(abs(explicit_residual) <= numerical_allowance,
            "Actual explicit-damping angular impulse does not match native pre/post angular momentum")
    # Also report the trapezoidal result with its predeclared endpoint envelope.
    envelope = B*sum(abs(row["omega_after_rad_s"]-row["omega_before_rad_s"])*row["dt_s"] for row in rows)/2
    tolerance = envelope+numerical_allowance
    return {"angular_momentum_change_Nms": change, "actual_motor_minus_load_impulse_Nms": impulse,
            "explicit_damping_impulse_Nms": before_damping, "implicit_damping_impulse_Nms": after_damping,
            "explicit_balance_residual_Nms": explicit_residual, "explicit_predeclared_tolerance_Nms": numerical_allowance,
            "midpoint_balance_residual_Nms": midpoint_residual, "endpoint_discretization_envelope_Nms": envelope,
            "predeclared_tolerance_Nms": tolerance}


def math_regressions():
    first = pid_update(-.8, DT, 2., 0., .35, .8, 2., 0., 0.)
    close(first["derivative"], -800., "Reset derivative kick")
    close(first["raw"], 281.6, "Reset raw PD command")
    close(first["command"], 2., "Actual output clipping includes derivative kick")
    saturated = pid_update(-4., DT, .4, .8, 0., .8, .35, -10., -4.)
    close(saturated["integral"], -1., "Integral-state back calculation from output I cap")
    close(saturated["i_term"], -.8, "Integral output cap")
    close(saturated["command"], .35, "Saturated output")
    close((.4*4-.2)/(.4+B), 2.8, "Default loaded P equilibrium")
    close((.8*4-.2)/(.8+B), 10/3, "Changed-gain loaded P equilibrium")
    rows = []
    omega = 0.
    for _ in range(100):
        after = omega+DT*(.4-B*omega)/J
        rows.append({"motor_command_Nm": .4, "load_torque_Nm": 0., "joint_applied_Nm": .4,
                     "dt_s": DT, "omega_before_rad_s": omega, "omega_after_rad_s": after})
        omega = after
    balance = momentum_metrics(rows)
    broken = [dict(row, motor_command_Nm=-.4) for row in rows]
    try:
        momentum_metrics(broken)
    except AssertionError:
        rejected = True
    else:
        raise AssertionError("Momentum checker accepted an intentionally reversed motor torque")
    return {"passed": True, "kind": "numerical_algorithm_regression_not_physics", "gazebo_started": False,
            "derivative_kick": first, "I_output_limit": saturated,
            "synthetic_Euler_impulse_balance": balance, "wrong_torque_sign_rejected": rejected}


