"""Registered course Markdown navigation, independent of experiment selection."""

from pathlib import Path
from urllib.parse import unquote, urlsplit

from PyQt5 import QtCore, QtGui, QtWidgets

from .markdown import render


class DocumentRegistry:
    def __init__(self, root, lessons):
        self.root = Path(root).resolve()
        self.paths = set()
        for lesson in lessons:
            for path in lesson.folder.rglob("*"):
                if path.suffix.lower() in (".md", ".markdown") and path.is_file():
                    resolved = path.resolve()
                    if self.root in resolved.parents and lesson.folder in resolved.parents:
                        self.paths.add(resolved)

    def resolve(self, current, target):
        parts = urlsplit(target)
        if parts.scheme or parts.netloc or parts.query:
            raise ValueError("只允许已登记课程内的 Markdown 文档链接。")
        path = (Path(current).parent / unquote(parts.path)).resolve() if parts.path else Path(current).resolve()
        # Resolve symlinks again on each click; the registry is not permission
        # to follow a path replaced since the catalog was loaded.
        if path not in self.paths or self.root not in path.parents or not path.is_file():
            raise ValueError("课程文档未登记、已移动或超出课程目录。")
        return path, unquote(parts.fragment)


class MarkdownReader(QtWidgets.QDialog):
    def __init__(self, registry, parent=None):
        super().__init__(parent)
        self.registry, self.history = registry, []
        self.current_path = None
        self.setObjectName("prerequisite_reader")
        self.setWindowTitle("前置知识 · 只读教材")
        self.resize(970, 730)
        layout = QtWidgets.QVBoxLayout(self)
        row = QtWidgets.QHBoxLayout()
        self.back_button = QtWidgets.QPushButton("返回上一份教材")
        self.back_button.setObjectName("reader_back")
        self.back_button.clicked.connect(self.go_back)
        row.addWidget(self.back_button)
        row.addWidget(QtWidgets.QLabel("只读阅读；当前课程与运行中的实验保持不变。"), 1)
        layout.addLayout(row)
        self.browser = QtWidgets.QTextBrowser()
        self.browser.setObjectName("prerequisite_document")
        self.browser.setOpenLinks(False)
        self.browser.setOpenExternalLinks(False)
        self.browser.anchorClicked.connect(self.open_link)
        layout.addWidget(self.browser, 1)
        self.location = QtWidgets.QLabel()
        self.location.setWordWrap(True)
        layout.addWidget(self.location)

    def display(self, path, fragment="", remember=True):
        path, unused = self.registry.resolve(path, "")
        if path.stat().st_size > 2 * 1024 * 1024:
            raise ValueError("教材超过只读阅读器的 2 MiB 上限。")
        if remember and self.current_path is not None:
            self.history.append((self.current_path, self.browser.verticalScrollBar().value()))
        self.current_path = path
        self.browser.document().setBaseUrl(QtCore.QUrl.fromLocalFile(str(path)))
        self.browser.setHtml(render(path.read_text(encoding="utf-8-sig")))
        self.location.setText(str(path.relative_to(self.registry.root)))
        self.back_button.setEnabled(bool(self.history))
        if fragment:
            self.browser.scrollToAnchor(fragment)

    def open_link(self, url):
        if url.scheme().lower() in ("http", "https"):
            QtGui.QDesktopServices.openUrl(url)
            return
        try:
            target = url.toString()
            if url.isLocalFile():
                path = Path(url.toLocalFile()).resolve()
                target = str(path) + ("#" + url.fragment() if url.hasFragment() else "")
                # Local absolute URL generated by QTextBrowser's base URL;
                # membership, containment and canonicalization still apply.
                if path not in self.registry.paths:
                    raise ValueError("目标不是已登记的课程教材。")
                path, fragment = self.registry.resolve(path, "#" + url.fragment())
            else:
                path, fragment = self.registry.resolve(self.current_path, target)
            self.display(path, fragment)
        except (OSError, ValueError) as error:
            self.location.setText("链接不可打开：" + str(error))

    def go_back(self):
        if self.history:
            path, position = self.history.pop()
            self.display(path, remember=False)
            self.browser.verticalScrollBar().setValue(position)
